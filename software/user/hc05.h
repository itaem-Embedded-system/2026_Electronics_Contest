#ifndef __HC05_H
#define __HC05_H

#include <stdint.h>
#include <stdbool.h>

/* =========================================================================
 * 1. 宏定义：通信协议常量
 * ========================================================================= */
#define BT_FRAME_HEADER1    0xAA   // 帧头 1
#define BT_FRAME_HEADER2    0x55   // 帧头 2
#define BT_FRAME_TAIL       0xFF   // 帧尾

// 指令类型定义（根据手机 App 的实际情况自行添加）
#define CMD_TYPE_JOYSTICK   0x01   // 摇杆连续控制指令
#define CMD_TYPE_ACTION     0x02   // 单次动作指令（如急停、鸣笛）
#define CMD_TYPE_YAW_TURN   0x03   // 相对 yaw 角度转向指令

/* =========================================================================
 * 2. 数据结构：解析后的有效指令
 * ========================================================================= */
typedef struct {
    uint8_t cmd_type;  // 接收到的指令类型
    int8_t  D1;     
    int8_t  D2;     
} BT_Ctrl_Cmd_t;

extern BT_Ctrl_Cmd_t g_bt_cmd;
/* =========================================================================
 * 3. 外部全局变量声明
 * ========================================================================= */
#if USE_BLUETOOTH
// 使用 extern 暴露该变量，让包含此头文件的所有任务都能无缝读取蓝牙数据


/* =========================================================================
 * 4. 外部可调用的函数声明
 * ========================================================================= */

/**
 * @brief 初始化 HC05 相关的消息队列和开启 UART 中断
 */
void HC05_Init(void);

/**
 * @brief FreeRTOS 蓝牙数据处理任务
 * @param pvParameters FreeRTOS 任务参数
 */
void Bluetooth_Task(void *pvParameters);
#endif // USE_BLUETOOTH

#endif /* __HC05_H */